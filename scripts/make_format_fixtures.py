"""Write the synthetic example profile in the raw-data layouts of common providers.

The genotypes are those of fixtures/synthetic-myheritage.txt and belong to no
real person. The comment lines imitate each provider's documented layout so the
importer can be tested; they are not copies of real files.
"""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
rows = [
    line.split(",")
    for line in (root / "fixtures/synthetic-myheritage.txt").read_text().splitlines()
    if line.startswith("rs")
]
out = root / "fixtures/formats"
out.mkdir(exist_ok=True)
CHR_NUMBER = {"X": "23", "Y": "24", "XY": "25", "MT": "26"}


def tsv(values):
    return "\t".join(values)


(out / "synthetic-23andme.txt").write_text(
    "# This data file was generated by 23andMe (synthetic example, no real person)\n"
    "# We are using reference human assembly build 37 (also known as Annotation Release 104).\n"
    "# rsid\tchromosome\tposition\tgenotype\n"
    + "".join(tsv([r, c, p, g if g != "--" else "--"]) + "\n" for r, c, p, g in rows)
)
(out / "synthetic-ancestrydna.txt").write_text(
    "#AncestryDNA raw data download (synthetic example, no real person)\n"
    "#Genetic data is provided below as five TAB delimited columns.\n"
    "#Chromosome positions are relative to human reference build 37.1.\n"
    "rsid\tchromosome\tposition\tallele1\tallele2\n"
    + "".join(
        tsv([r, CHR_NUMBER.get(c, c), p, *(list(g) if len(g) == 2 and g != "--" else ["0", "0"])]) + "\n"
        for r, c, p, g in rows
    )
)
(out / "synthetic-livingdna.txt").write_text(
    "# Living DNA customer genotype data download file (synthetic example, no real person)\n"
    "# Human Genome Reference Build 37 (GRCh37.p13)\n"
    "# rsid\tchromosome\tposition\tgenotype\n"
    + "".join(tsv([r, c, p, g]) + "\n" for r, c, p, g in rows)
)
# FamilyTreeDNA files carry no comment lines and no declared build.
(out / "synthetic-familytreedna.csv").write_text(
    "RSID,CHROMOSOME,POSITION,RESULT\n"
    + "".join(f'"{r}","{c}","{p}","{g}"\n' for r, c, p, g in rows)
)
print("\n".join(sorted(p.name for p in out.iterdir())))
